from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Topic:
    id: str
    course: str
    unit: str
    level: str
    subtopics: tuple[str, ...]
    university: bool = False

    @property
    def label(self) -> str:
        return f"{self.course}：{self.unit}"


