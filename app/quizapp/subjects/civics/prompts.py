QUESTION_SYSTEM = """あなたは日本の高校の「公共」（大学入学共通テストの「公共」）の問題を作る編集者です。
与えられた資料（法令の条文、または百科事典の記事の一部）を読んで答える 4 択の設問を作ります。資料は書き換えません。

設問:
- 正解は資料の内容だけから 1 つに決まるようにする。生徒は資料を読みながら解く
- 「資料の内容に合うもの」「〜について資料から読み取れること」「〜の場合にあてはまるもの」など、合うものを 1 つ選ばせる形にする。「誤っているもの」「適当でないもの」を選ばせる設問は作らない
- 条文の要件（誰が・何を・どんな場合に・どれだけ）や、用語の意味・しくみの違いを問う。資料の言葉を探すだけで終わらず、具体的な場面にあてはめる設問もよい
- 意見が分かれるテーマ（憲法改正、安全保障、原子力、死刑など）では、どちらが正しいかを決めつけない。制度のしくみや、資料に書かれた立場・主張の中身を問う。生徒の意見・賛否・価値判断を問わない
- 資料の中の意見・推測・批判（「〜と思われる」「〜と批判されている」「〜という疑念が生じた」など）を、事実として正解にしない。事実・制度のしくみ・定義を述べた文を根拠にする
- 時点のある数値・順位・「現在」の状況を問う設問・選択肢には「資料の時点で」を付ける（資料が書かれた後に変わっていることがある）

選択肢:
- 正解の選択肢は、資料の言葉をそのまま写さず言い換える。正解のどの部分も資料で裏付けられるようにする（資料にない要素を足さない）。言い換えで意味を変えない：資料の条件（「〜の場合」）を落とさない、理由・目的を別の事柄に付け替えない、「政令の定めるところにより」のような手続きの言葉を「政令で定められた数」のように別の意味にしない
- **誤答は、資料の上でも現実でも明らかに誤りにする**。「資料には書かれていないが現実には正しい」「ほぼ正しい」「見方によっては正しい」誤答は作らない（正解が 2 つになる）
- **資料のほかの箇所に書かれている正しい内容を、誤答にしない**。誤答は、資料の特定の語（数・年・主体・増減・肯定と否定・対象）を、逆か別の値に変えて作る。言い換えただけ・限定の語を足したり外したりしただけ・資料の 2 つの文をつないだだけの文は誤答にならない（例：資料「市ごとに 0〜10%」に対する「州ごとに 0〜10%」、資料「努めなければならない」に対する「義務付けている」、資料「法律で定める」に対する「国会が定める」は、どれも誤りと言えない）
- 誤答を書いたら、資料を読み直して「資料のこの語と食い違う」と指させるかを確かめる。指させない誤答は書き直す
- 誤答 3 つは、それぞれ別の誤り方にする（同じ記述の同じ点を突く誤答を 2 つ作らない）
- 「〜の状態」「〜を超えている」「〜以上」のような選択肢では、誤答が資料の定義・基準を満たしてしまわないかを確かめる（例：「40% を超えたら寡占」なら「85% を超えている」も寡占にあてはまる）。基準そのものを問うときは、選択肢を基準の値にする
- 修飾する語がどこにかかるか曖昧な書き方をしない（「A の機関である、B の後継」→「A の機関だった B を引き継いで設立された」）
- 法律の条文を言い換えるときは、意味が逆に読める省略をしない（「刑法の規定が適用される」→「刑法第 35 条（正当行為は罰しない）の規定が適用される」）
- 4 つの選択肢の長さをそろえる。「すべて正しい」のような選択肢は作らない。すでにある設問と同じこと・同じ誤答は作らない
- 選択肢は A〜D の 4 つ。誤答それぞれに、間違いの種類を次の記号で付ける:
  contradicts（資料と食い違う：資料に書かれている内容と反対・矛盾する。主体・目的・時期が資料と違うものも含む）
  not_stated（資料にまったく触れられていない内容で、事実としても誤り。資料に反対の内容が書かれていれば contradicts にする）
  partial（一部は資料どおりで、一部が資料と違う。どこも資料と合わない誤答は partial にしない）
  detail（数・日付などの細かい点だけが資料と違う）
- Evidence には、正解の根拠になる資料の 1 文を、資料から一字一句そのまま写す（言い換えない・つなげない・省略しない）。正解に年・数値・順位があれば、その年・数値が書かれた文にする

理由とヒント（解説は、選択肢ごとの理由から組み立てて表示する）:
- Why A〜Why D には、その選択肢が正しい・誤りである理由を 1〜2 文で書く。正解の理由は、根拠になる資料の部分とともに書く
- 誤答の理由は、その選択肢の言葉をそのまま使って否定する（別の語にすり替えない）。根拠には、その選択肢と同じ時期・主体・事柄について書いた資料の部分を挙げる（別の時期・別の話の文を根拠にしない）
- 資料から引いた言葉は「資料に『〜』とある」のように書き、選択肢の言葉と区別する
- 理由の中で、ほかの選択肢を A・B などの記号で呼ばない（選択肢は画面で並べ替える）
- ヒントは答えを書かずに、資料のどこを読めばよいか（第◯条、第◯段落、「〜から〜にかけての変化」など）を 1〜2 文で示す。正解の選択肢にある語句（人名・出来事・制度の名前・年・数値など）はヒントに書かない
- 誤答の理由を「〜とは書かれていない」「〜とは限らない」「不十分である」だけで終わらせない。資料のどの語と食い違うかを書く（書けないなら、その誤答が誤りになっていない）
- 資料の内容と食い違うことを書かない。資料にない知識を足すときは、確かな事実だけを短く書く
- 資料は「資料」と呼ぶ。自然な日本語で書く（中国語の字や言い回しを混ぜない）
- 生徒が読む文章なので、作成の指示やこのアプリの言葉（「与えられた」「指示」「指定された」など）は書かない

各設問の欄は、次の形で 1 行ずつ書く:
Question: <設問>
A: <選択肢>
B: <選択肢>
C: <選択肢>
D: <選択肢>
Answer: <正解の記号 1 文字>
Wrong: <誤答の記号>=<種類>, <誤答の記号>=<種類>, <誤答の記号>=<種類>
Evidence: <資料から写した根拠の 1 文>
Why A: <選択肢 A が正しい・誤りである理由>
Why B: <選択肢 B の理由>
Why C: <選択肢 C の理由>
Why D: <選択肢 D の理由>
Hint: <ヒント>"""


def question_schema(n_questions: int) -> dict[str, Any]:
    props = {f"q{i}": {"type": "string",
                       "description": f"設問 {i}（Question・A〜D・Answer・Wrong・Evidence・Why A〜Why D・Hint の各行）"}
             for i in range(1, n_questions + 1)}
    return {"type": "object", "properties": props, "required": list(props)}


# 共通テストのレベルの小単元で足す指示（第 13 回・第 14 回のレビュー：1 文を探せば解ける設問ばかりで、難易度が一段低かった）
COMBINE = ("共通テストのレベルなので、半分以上の設問を、資料の 2 か所以上の記述を組み合わせて判断する設問にする"
           "（2 つの制度・国・時期の違いの比較、理由と結果のつながりなど）。Evidence にはその中心になる 1 文を写す")


def question_user(title: str, body: str, n_questions: int, focus: str, existing: list[str] | list[dict[str, Any]],
                  level: str = "", fetched: str = "") -> str:
    lines = [f"資料の題名: {title}" + (f"（{fetched} に取得）" if fetched else ""), "資料:", body, "",
             f"作る設問の数: {n_questions}（[[q1]] から [[q{n_questions}]] まで。それぞれ資料の別の部分を問う）",
             f"この単元で問いたいこと: {focus}"]
    if level == "common":
        lines.append(COMBINE)
    if existing:
        lines += ["", "この資料にすでにある設問（同じことを問わない。同じ内容を正解にしない。同じ誤答を作らない）:"]
        for q in existing:
            if isinstance(q, dict):
                lines.append(f"- {q.get('question', '')}（選択肢：{'／'.join(q.get('choices', []))}）")
            else:
                lines.append(f"- {q}")
    return "\n".join(lines)


def why_user(body: str, q: dict[str, Any], note: str = "") -> str:
    """選択肢ごとの理由とヒントだけを書き直させる（理由が空・短い、見直しで指摘された。第 14 回のレビュー 3 章 F）。"""
    letters = "ABCD"
    options = "\n".join(f"{letters[i]}. {t}" for i, t in enumerate(q["options"]))
    lines = ["資料:", body, "", "設問: " + q["question"], options, "正解: " + letters[q["answer"]],
             "正解の根拠の文: " + q["evidence"]]
    if note:
        lines += ["", "直してほしい点: " + note]
    lines += ["", "設問・選択肢・正解は変えずに、選択肢ごとの理由（Why A〜Why D）とヒント（Hint）だけを書き直してください。"
              "1 行ずつ「Why A: …」「Why B: …」「Why C: …」「Why D: …」「Hint: …」の形で書く。"]
    return "\n".join(lines)


def swap_user(body: str, q: dict[str, Any], bad: dict[str, str]) -> str:
    """検証で「資料で裏付けられる・事実として正しい」とされた誤答だけを作り直させる（設問・正解・ほかの選択肢は
    変えない。第 16 回のレビュー 3 章 B）。bad＝{記号: 検証役の指摘}。"""
    letters = "ABCD"
    options = "\n".join(f"{letters[i]}. {t}" for i, t in enumerate(q["options"]))
    lines = ["資料:", body, "", "設問: " + q["question"], options, "正解: " + letters[q["answer"]],
             "正解の根拠の文: " + q["evidence"], "", "誤答のうち、次の選択肢は誤りになっていませんでした（資料で裏付けられる・事実として正しい）:"]
    lines += [f"- {c}: {note}" for c, note in bad.items()]
    lines += ["", f"設問・正解・ほかの選択肢は変えずに、選択肢 {'・'.join(bad)} だけを、資料の上でも現実でも明らかに誤りの文に"
              "書き直してください。資料の特定の語（数・年・主体・増減・肯定と否定）を逆か別の値に変えて作り、ほかの選択肢と"
              "同じ誤り方にしない。長さはほかの選択肢にそろえる。",
              "書き直す選択肢ごとに、1 行ずつ「A: <新しい選択肢>」「Why A: <誤りである理由。資料のどの語と食い違うか>」の形で書き、"
              "最後に「Wrong: A=contradicts」の形で間違いの種類（contradicts・not_stated・partial・detail）を書く。"]
    return "\n".join(lines)


