REVIEW_SYSTEM = """あなたは日本の高校の「公共」の先生です。生徒に出す前に、資料を読んで答える問題の解説を点検します。
解説は、選択肢ごとの理由として示します。次の点を 1 つずつ確かめてください。
1. 理由・ヒントの内容が資料と合っているか。条文の主体・条件・数（誰が・何を・どんな場合に）を取り違えていないか
2. 正解の理由が、資料の根拠とともに説明されているか。「資料の根拠」の文が、正解を裏付ける文か（別の年・別の事柄の文でないか）
3. 誤答の理由が、その選択肢の言葉をそのまま使って否定しているか（別の語にすり替えていないか。例：選択肢が「私的独占」なのに、理由が「不当な取引制限ではない」と否定している）
4. 誤答の理由に挙げた資料の部分が、その選択肢と同じ時期・主体・事柄を述べた文か（別の時期の出来事や、別のことを述べた文を根拠にしていないか）
5. 理由の中で、資料の引用と選択肢の言葉が区別されているか（どれが資料でどれが選択肢か読み取れるか）
6. ヒントが正解の場所を正しく示しているか（答えそのものや、正解の選択肢の語句を書いていないか。誤答の側を指していないか）
7. 理由が、資料にない誤った知識や、古い制度を今のもののように書いていないか。資料にない知識で補足すること自体は誤りではない（例：「刑法第 35 条は、正当な行為は罰しないという規定」）。補足が事実と違うときだけ指摘する
10. 誤答の理由が、その選択肢自身の文を扱っているか（別の選択肢の文を引いて否定していないか）
8. 意見が分かれるテーマで、どれかの立場を正しいと決めつけていないか（設問・選択肢・理由とも）
9. 設問・選択肢・理由が自然な日本語か
細かい言い回しの好みや、もっと良い書き方がある、根拠にはこちらの文のほうが良い、というだけのものは誤りとしない。指摘の前に、資料にその記述が本当にないか・あるかを資料で確かめる。

verdict の 1 行目には「問題なし」か「問題あり」のどちらかだけを書く。issues には、直すべき点を選択肢の文を挙げて具体的に書く。"""


def review_user(title: str, passage: str, question: str, choices: list[dict[str, Any]], explanation: str,
                hint: str, evidence: str = "") -> str:
    lines = [f"資料の題名: {title}", "資料:", passage, "", "問題:", question, "", "選択肢と理由:"]
    have_why = any(c.get("why") for c in choices)
    for c in choices:
        mark = "（正解）" if c.get("correct") else ""
        lines.append(f"- 「{c.get('text', '')}」{mark}" + (f"\n  理由: {c.get('why', '')}" if have_why else ""))
    if evidence:
        lines += ["", f"資料の根拠: 「{evidence}」"]
    if not have_why:  # 前の版の問題（選択肢ごとの理由がない）
        lines += ["", "解説:", explanation]
    lines += ["", "ヒント:", hint]
    return "\n".join(lines)
